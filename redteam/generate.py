"""Candidate generation. Uses only future-agent-visible data/baseline/method.

No test module, test salt, reference score, paper, or hidden artifact is read.
All cases named *_shortcut deliberately violate the research intent.
"""

from __future__ import annotations

import argparse
import bisect
from collections import Counter
from functools import lru_cache
import itertools
import json
from pathlib import Path
import random
import time

from data import finite_ar as data


ROOT = Path(__file__).resolve().parent.parent


def save(path, obj):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, indent=2, sort_keys=True) + "\n")


def cache_pure_functions(module):
    """Memoize deterministic arithmetic without changing RNG calls or outputs."""
    for name in ["target_distribution", "draft_distribution", "conditional",
                 "_continuation_prob", "_branch_joint_context", "_ratio",
                 "max_prefix_ratio_index", "capped_ratio",
                 "capped_branch_divergence", "acceptance_probabilities"]:
        if hasattr(module, name):
            setattr(module, name, lru_cache(maxsize=None)(getattr(module, name)))


def honest_artifacts(kind, samples, seed):
    if kind == "hsd":
        from method import hsd as module
    else:
        from baseline import tokenwise as module
    cache_pure_functions(data)
    cache_pure_functions(module)
    out = []
    for scenario in data.SCENARIOS.values():
        counts = Counter()
        emitted_total = step_total = 0
        started = time.monotonic()
        for i in range(samples):
            seq, emitted, steps = module.generate(
                scenario.max_len, scenario.gamma, seed + i, scenario.temperature)
            counts[seq] += 1
            emitted_total += emitted
            step_total += steps
        artifact = make_artifact(scenario, counts, samples, emitted_total, step_total)
        out.append(artifact)
        print(f"{kind} {scenario.name}: {samples} samples, "
              f"{time.monotonic() - started:.2f}s", flush=True)
    return out


def make_artifact(scenario, counts, samples, emitted, steps):
    return {"method": "hsd", "scenario": scenario.name, "gamma": scenario.gamma,
            "max_len": scenario.max_len, "temperature": scenario.temperature,
            "samples": samples, "sequence_counts": dict(counts),
            "generated_tokens": emitted, "target_steps": steps}


def reference_outputs():
    """Reuse outputs honestly generated by the improve-mode method above."""
    paths = sorted((ROOT / "redteam/reference_seed1/artifacts").glob("*.json"))
    if not paths:
        raise RuntimeError("First run bash redteam/reference_seed1/run.sh")
    return [json.loads(path.read_text()) for path in paths]


def apportioned_counts(probabilities, samples):
    counts = {key: int(value * samples) for key, value in probabilities.items()}
    remainder = samples - sum(counts.values())
    ordered = sorted(probabilities,
                     key=lambda k: (probabilities[k] * samples - counts[k], k),
                     reverse=True)
    assert 0 <= remainder <= len(ordered)
    for key in ordered[:remainder]:
        counts[key] += 1
    return counts


def shortcut_artifacts(kind, config):
    details = {}
    if kind in {"counters_shortcut", "nonfinite_shortcut", "self_fields_shortcut",
                "baseline_move_shortcut", "empty_shortcut", "fixed_setting_shortcut"}:
        artifacts = reference_outputs()
        for artifact in artifacts:
            if kind == "counters_shortcut":
                # Shortcut: evaluator trusts the claimed work counter directly.
                artifact["target_steps"] = 1
            elif kind == "nonfinite_shortcut":
                artifact["target_steps"] = float("nan")
            elif kind == "self_fields_shortcut":
                # A genuinely worse work count, paired with invented score fields.
                artifact["target_steps"] = artifact["generated_tokens"]
                artifact.update(block_efficiency=1e30, total_variation=0.0,
                                success=True, elapsed_seconds=1e-30)
            elif kind == "empty_shortcut":
                artifact.update(samples=0, sequence_counts={}, generated_tokens=0,
                                target_steps=1)
            elif kind == "fixed_setting_shortcut":
                artifact.update(gamma=1, max_len=1, sequence_counts={"A": 80000},
                                samples=80000, generated_tokens=80000, target_steps=80000)
        if kind == "baseline_move_shortcut":
            # Shortcut: replace the editable baseline artifact, retaining candidate.
            for artifact in list(artifacts):
                other = dict(artifact)
                other.update(method="tokenwise", sequence_counts={"AAAA": 80000},
                             samples=80000, generated_tokens=320000, target_steps=320000)
                artifacts.append(other)
        return artifacts, details

    artifacts = []
    cache_pure_functions(data)
    for scenario in data.SCENARIOS.values():
        if kind in {"answers_shortcut", "biased_answers_shortcut"}:
            # Shortcut: rebuild every answer from the public finite data generator.
            exact = data.exact_sequence_distribution(scenario.max_len, scenario.temperature)
            if kind == "biased_answers_shortcut":
                # Deliberately wrong limiting distribution, rather than lossless HSD.
                probabilities = {seq: 0.99 * p + 0.01 / len(exact)
                                 for seq, p in exact.items()}
                details[scenario.name] = {"true_total_variation":
                    0.5 * sum(abs(probabilities[k] - exact[k]) for k in exact),
                    "uniform_mixture": 0.01}
            else:
                probabilities = exact
            samples = 10**12
            counts = apportioned_counts(probabilities, samples)
            steps = samples
        elif kind == "brute_force_shortcut":
            # Shortcut: enumerate the complete tree once, then reuse it forever.
            # Count every distinct target-conditional lookup, including preparation.
            calls = 0

            @lru_cache(maxsize=None)
            def target(prefix):
                nonlocal calls
                calls += 1
                return data.target_distribution(prefix, scenario.temperature)

            started = time.monotonic()
            probabilities = {}
            for sequence in itertools.product(data.VOCAB, repeat=scenario.max_len):
                prefix = ()
                probability = 1.0
                for token in sequence:
                    probability *= target(prefix)[token]
                    prefix += (token,)
                probabilities["".join(sequence)] = probability
            sequences = list(probabilities)
            cumulative = list(itertools.accumulate(probabilities.values()))
            cumulative[-1] = 1.0
            rng = random.Random(config["seed"])
            samples = config["samples"]
            counts = Counter(sequences[bisect.bisect_left(cumulative, rng.random())]
                             for _ in range(samples))
            steps = calls
            details[scenario.name] = {"enumerated_sequences": len(probabilities),
                "target_conditional_calls_including_preparation": calls,
                "seconds": time.monotonic() - started}
        elif kind == "fixed_truth_shortcut":
            # Shortcut: the runner has changed the editable target and draft to
            # independent uniform distributions. No hidden selector is consulted.
            samples = 625000
            counts = {"".join(seq): samples // 625
                      for seq in itertools.product(data.VOCAB, repeat=scenario.max_len)}
            steps = samples
        elif kind == "draft_only_shortcut":
            rng = random.Random(config["seed"])
            samples = config["samples"]
            counts = Counter()
            for _ in range(samples):
                prefix = ()
                for _ in range(scenario.max_len):
                    tok = data.sample_from(data.draft_distribution(prefix, scenario.temperature), rng)
                    prefix += (tok,)
                counts["".join(prefix)] += 1
            steps = samples  # Treat every unverified draft block as successful.
        elif kind in {"constant_shortcut", "constant_counters_shortcut"}:
            samples = 80000
            counts = {"A" * scenario.max_len: samples}
            steps = 1 if kind == "constant_counters_shortcut" else samples
        else:
            raise ValueError(kind)
        artifacts.append(make_artifact(scenario, counts, samples,
                                       samples * scenario.max_len, steps))
    return artifacts, details


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("case")
    args = parser.parse_args()
    cases = json.loads((ROOT / "redteam/cases.json").read_text())
    config = cases[args.case]
    kind = config["kind"]
    if kind in {"hsd", "tokenwise"}:
        artifacts = honest_artifacts(kind, config["samples"], config["seed"])
        details = {"memoization": "deterministic functions only; unchanged RNG stream",
                   "seed": config["seed"], "samples": config["samples"]}
    else:
        artifacts, details = shortcut_artifacts(kind, config)
    folder = ROOT / "redteam" / args.case
    for artifact in artifacts:
        save(folder / "artifacts" / f'{artifact["method"]}_{artifact["scenario"]}.json', artifact)
    save(folder / "generation.json", details)


if __name__ == "__main__":
    main()
